// Builds src/core/hans-map.js: the 繁 → 简 character map for the characters the game and the site actually use (OpenCC
// tw → cn, one character at a time, a few context fixes below). The text is written in 繁體; core/lang.js shows it in
// 简体 through this map. Run after adding text with new characters: node tools/hans.mjs (needs opencc-js:
// npm i -D opencc-js, or NODE_PATH to a folder that has it).
import fs from 'fs';
import path from 'path';
import * as OpenCC from 'opencc-js';

const root = path.resolve(import.meta.dirname, '..');
const files = [];
const walk = (d) => { for (const f of fs.readdirSync(d)) { if (f.startsWith('.') || f.startsWith('_')) continue; const p = path.join(d, f); if (fs.statSync(p).isDirectory()) walk(p); else if (/\.(js|html)$/.test(f)) files.push(p); } };
walk(path.join(root, 'src')); files.push(path.join(root, 'index.html'), path.join(root, 'site/index.html'));
const CJK = /[㐀-䶿一-鿿豈-﫿]/g;
const chars = new Set();
for (const f of files) { if (f.endsWith('hans-map.js')) continue; for (const c of fs.readFileSync(f, 'utf8').match(CJK) || []) chars.add(c); }
const conv = OpenCC.Converter({ from: 'tw', to: 'cn' });
// one character out of context: keep these as they are (乾坤, 著名 …)
const KEEP = new Set(['乾', '藉', '瞭']);
const pairs = [];
for (const c of [...chars].sort()) {
  if (KEEP.has(c)) continue;
  const s = conv(c);
  if (s !== c && [...s].length === 1) pairs.push(c + s);
}
const out = `// Generated by tools/hans.mjs — 繁 → 简 for the characters in use (pairs: traditional, simplified). Do not edit.\nexport const T2S = '${pairs.join('')}';\n`;
fs.writeFileSync(path.join(root, 'src/core/hans-map.js'), out);
console.log(`${chars.size} characters in use, ${pairs.length} pairs → src/core/hans-map.js (${out.length} B)`);
